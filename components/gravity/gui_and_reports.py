    def _refresh_case_reaction(self):
        """Only display a valid, previously solved case-specific support reaction.

        [REF docs/source/components/gravity/reaction_case_registry.py.md]
        """
        self.solved_reaction_var.set("Not analyzed for this case")
        self.solved_reaction_status_var.set("No matching completed run; run the selected case")
        try:
            from components.gravity.reaction_case_registry import current_case
            model=Path(self.model_var.get()).expanduser().resolve()
            root=Path(self.output_var.get()).expanduser().resolve()
            if not model.is_file():
                return
            scenario=self._selected_wall_support_strategy()
            profile=self.gravity_profile_var.get()
            expected=None
            if scenario=="ETABS_NONZERO_REACTION_DIAGNOSTIC":
                from components.gravity.etabs_reaction_support_filter import PROJECT_PRIMARY_32
                expected=PROJECT_PRIMARY_32
            elif scenario=="ETABS_SOURCE_SUPPORTS":
                tags=self.position_support_var.get().strip()
                if tags:
                    expected=[int(x.strip()) for x in tags.split(",") if x.strip()]
            record=current_case(root,model,scenario=scenario,profile=profile,
                                expected_support_tags=expected)
            if record is None:
                self.solved_reaction_status_var.set(
                    "Not analyzed / model or load profile changed / output unavailable")
                return
            self.solved_reaction_var.set(f"{record['summed_reaction_kN']:.6f}")
            self.solved_reaction_status_var.set(
                f"{record['support_count']} solved supports | "
                f"equilibrium difference {record['equilibrium_error_percent']:.6g}% | "
                f"{'CHECK EQUILIBRIUM' if not record['balance_pass'] else 'numerical equilibrium OK'} | "
                f"NOT ETABS VALIDATED")
        except (OSError,KeyError,ValueError,TypeError) as error:
            self.solved_reaction_status_var.set("Reaction unavailable: "+str(error))

    def _inputs(self):
        model = Path(self.model_var.get()).expanduser().resolve()
        report_path = model.parent / 'OpenSees_Complete_Export_Report_V118.json'
        if model.name.startswith('OpenSees_Complete_') and report_path.is_file():
            errors = json.loads(report_path.read_text(encoding='utf-8-sig')).get('assembly_errors', [])
            if errors: raise ValueError('Model assembly blocked: ' + '; '.join(errors) + '. Rebuild with the latest exporter. Manual support inputs cannot repair assembly.')
        out = Path(self.output_var.get()).expanduser().resolve()
        py = Path(self.python_var.get()).expanduser().resolve()
        if not model.is_file(): raise ValueError("Select an existing generated OpenSees model script.")
        if not py.is_file(): raise ValueError("Select a valid Python executable with OpenSeesPy installed.")
        if not out.exists(): out.mkdir(parents=True, exist_ok=True)
        try:
            supports = [int(x.strip()) for x in self.support_var.get().replace(";", ",").split(",") if x.strip()]
            total = float(self.load_var.get()); steps = int(self.steps_var.get())
        except ValueError as exc: raise ValueError("Enter comma-separated integer support tags, a numeric load in kN, and an integer step count.") from exc
        if not supports or total <= 0 or steps < 1: raise ValueError("Support tags, positive applied load and at least one load step are required.")
        if len(set(supports)) != len(supports): raise ValueError("Support node tags contain duplicates; each support must appear once.")
        # Source model and original ETABS table are authoritative; never permit
        # stale manual support editing to silently change the structural model.
        import json as _json
        assembled=_json.loads((model.parent/"OpenSees_Complete_Model_Data_V118.json").read_text(encoding="utf-8-sig"))
        original=sorted(int(tag) for tag,flags in assembled["supports"].items() if flags[2])
        policy=self._selected_wall_support_strategy()
        if policy=="ETABS_NONZERO_REACTION_DIAGNOSTIC":
            if self.gravity_profile_var.get()!="GRAVITY_1.0D_1.0L":
                raise ValueError("Nonzero reaction diagnostic must use full 1D+1L")
            from components.gravity.etabs_reaction_support_filter import classify_supports
            table=self.etabs_full_table_var.get().strip()
            selected,_audit=classify_supports(
                table,model.parent/"OpenSees_Element_Connectivity.json",assembled["supports"])
            expected_supports=sorted(map(int,selected))
        else:
            expected_supports=original
        if sorted(supports)!=expected_supports:
            raise ValueError("Displayed supports do not match authoritative selected scenario. Click Read BOTH support lists; no manual unreviewed fixity changes.")
        # Recalculate before every run; reject stale manually entered totals.
        expected, context, _ = self._selected_gravity_evidence(model)
        if abs(total-expected)>max(0.01,abs(expected)*1e-7):
            raise ValueError("Displayed total differs from source-derived "+context['profile']+
                             " load: expected "+str(expected)+" kN, entered "+str(total)+
                             " kN. Refresh the selected model and its gravity inputs.")
        return model, out, py, supports, expected, steps

    def run(self):
        try: model, out, py, supports, total, steps = self._inputs()
        except Exception as exc:
            messagebox.showerror("Gravity inputs need review", str(exc), parent=self.win); return
        if not self.coverage_confirmed.get():
            messagebox.showerror("Gravity load coverage not confirmed", "Review the generated model and verify the total downward load against the project load ledger. The code-derived line-load total may omit slab, wall, self-weight, FVD/BRB or other loads. Confirm coverage before running.", parent=self.win); return
        self.run_button.configure(state="disabled")
        self.status_var.set("Running model and nonlinear gravity steps…")
        self.log.delete("1.0", "end")
        self._gravity_action_log("GRAVITY_START","Selected model: "+str(model))
        self._gravity_action_log("GRAVITY_SUPPORTS","Wall base strategy="+self._selected_wall_support_strategy())
        self._gravity_action_log("GRAVITY_SETTINGS",f"Profile={self.gravity_profile_var.get()} | "
            f"Downward load={total:.6f} kN | supports={len(supports)} | steps={steps}")
        self._gravity_action_log("GRAVITY_OUTPUT","Result and run logs: "+str(out))
        self._gravity_action_log("GRAVITY_UPLOAD_DESTINATION",
            str(out/"Gravity_Evidence_Upload"))
        self._gravity_action_log("GRAVITY_GUI_LOG",
            str(out/"Gravity_GUI_Actions.log"))
        self.log.insert("end",f"Support tags: {supports}\n")
