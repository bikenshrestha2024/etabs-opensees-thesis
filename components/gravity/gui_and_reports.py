    def _worker(self, py, runner, result_path, log_path, out, profile, support_strategy="ETABS_SOURCE_SUPPORTS"):
        try:
            proc = subprocess.run([str(py), str(runner)], cwd=str(out), capture_output=True, text=True, errors="replace", env={**dict(__import__('os').environ),'PYTHONIOENCODING':'utf-8','PYTHONUTF8':'1','OPENSEES_GRAVITY_PROFILE':profile,
                'OPENSEES_GRAVITY_GUI_MODE':'1',
                'OPENSEES_GRAVITY_WALL_SUPPORT_STRATEGY':support_strategy,
                'OPENSEES_GRAVITY_ETABS_TABLE':str(self.etabs_full_table_var.get().strip()) if support_strategy=='ETABS_NONZERO_REACTION_DIAGNOSTIC' else '',
                'OPENSEES_GRAVITY_AUDIT_DIR':str(out) if support_strategy=='ETABS_NONZERO_REACTION_DIAGNOSTIC' else ''}, encoding='utf-8')
            combined = proc.stdout + ("\n--- STDERR ---\n" + proc.stderr if proc.stderr else "")
            log_path.write_text(combined, encoding="utf-8")
            if not result_path.exists():
                payload = {"ok": False, "error": f"Runner exited {proc.returncode} without a result JSON."}
            else:
                payload = json.loads(result_path.read_text(encoding="utf-8"))
            if proc.returncode != 0: payload["ok"] = False
            payload["_process_returncode"]=proc.returncode
            self.win.after(0, lambda: self._finished(payload, combined, out))
        except Exception as exc:
            detail = traceback.format_exc()
            try: log_path.write_text(detail, encoding="utf-8")
            except Exception: pass
            self.win.after(0, lambda: self._finished({"ok": False, "error": str(exc)}, detail, out))

    def _finished(self, payload, log_text, out):
        self.run_button.configure(state="normal")
        self._gravity_action_log("GRAVITY_SOLVER","Full OpenSees console log follows")
        self.log.insert("end", "\n" + log_text + "\n")
        self.log.see("end")
        if not payload.get("ok"):
            self._gravity_action_log("GRAVITY_FAILED_SOLVER_LOG",str(out/"Gravity_Run_V110.log"))
            self._gravity_action_log("GRAVITY_FAILED_RESULT",str(out/"Gravity_Result_V110.json"))
            self._gravity_action_log("GRAVITY_GUI_LOG",str(out/"Gravity_GUI_Actions.log"))
            self.status_var.set("Gravity run failed — see the log for the failing step.")
            messagebox.showerror("Gravity analysis failed", payload.get("error", "Unknown error"), parent=self.win)
            self.nb.select(self.log_tab)
            return
        try:
            paths = self._make_outputs(payload, out)
        except Exception as exc:
            self.status_var.set("Analysis passed; report generation failed.")
            messagebox.showerror("Report generation failed", str(exc), parent=self.win)
            self.nb.select(self.log_tab)
            return
        if payload.get("wall_support_strategy")=="ETABS_NONZERO_REACTION_DIAGNOSTIC":
            try:
                from components.gravity.etabs_reaction_support_filter import export_primary_32_comparison
                summary=export_primary_32_comparison(
                    payload,out/"ETABS_Nonzero_Reaction_Support_Audit.json",out)
                self._gravity_action_log("PRIMARY_32_REACTION_COMPARISON",
                    f"ETABS={summary['etabs_total_FZ_kN']:.6f} kN; "
                    f"OpenSees={summary['opensees_total_FZ_kN']:.6f} kN; "
                    f"delta={summary['global_difference_kN']:.6f} kN; "
                    f"worst node={summary['worst_node']}; "
                    f"status={summary['numerical_agreement']} / "
                    f"{summary['structural_validation']}")
                for ext in ("xlsx","csv","json"):
                    self._gravity_action_log("PRIMARY_32_REACTION_OUTPUT",
                        str(out/("Primary_32_ETABS_OpenSees_Reactions."+ext)))
            except Exception as comparison_exc:
                self._gravity_action_log("PRIMARY_32_COMPARISON_FAILED",str(comparison_exc))
                messagebox.showerror("Gravity solved, comparison not validated",
                    "Gravity solver passed but node-by-node comparison failed: "+
                    str(comparison_exc),parent=self.win)
                self.nb.select(self.log_tab)
                return
        rep = payload["report"]
        self._gravity_action_log("GRAVITY_EQUILIBRIUM",str({
           "applied_vertical_kN":rep.get("applied_vertical_load_kN"),
           "support_reaction_kN":rep.get("support_vertical_reaction_kN"),
           "equilibrium_error_percent":rep.get("equilibrium_error_percent"),
           "max_downward_uz_m":rep.get("max_downward_uz_m"),
           "frozen":rep.get("frozen"),
           "elapsed_seconds":rep.get("elapsed_seconds")}))
        self._gravity_action_log("GRAVITY_EXPORT","Generated gravity result report and workbook/plots in "+str(out))
        for filename in ("Gravity_Result_V110.json","Gravity_Run_V110.log","Gravity_Results_V110.xlsx"):
            self._gravity_action_log("GRAVITY_OUTPUT_FILE",str(out/filename))
        for path in paths:
            if Path(path).is_file() and Path(path).name not in (
                "Gravity_Result_V110.json","Gravity_Run_V110.log","Gravity_Results_V110.xlsx"):
                self._gravity_action_log("GRAVITY_FIGURE_FILE",str(path))
        try:
            self._publish_gravity_evidence(single_run=out)
        except Exception as pack_exc:
            self._gravity_action_log("EVIDENCE_EXPORT_ERROR",
                "Gravity solver passed; upload ZIP failed: "+str(pack_exc))
        self.status_var.set(f"Gravity PASS | equilibrium error {rep['equilibrium_error_percent']:.4g}% | {rep['elapsed_seconds']:.2f} s | outputs saved in {out}")
        self.nb.select(self.plot_tab)
        messagebox.showinfo("Gravity analysis complete", "Gravity converged; reaction check passed; gravity frozen at time zero.\n\nExcel workbook, separate 300 dpi PNG/PDF figures and critical-action PDF saved.\nUse the result tabs or Open output folder to inspect them.\n\n" + str(out), parent=self.win)

