    def _selected_gravity_evidence(self, model):
        """Read fresh unfactored source loads; never reuse the 0.30 preload total.

        [REF components/model/assembly.py apply_gravity_profile]
        Independent 1D+1L+roof-live comparison leaves seismic mass unchanged.
        """
        from OpenSees_Complete_Export_V118 import apply_gravity_profile
        from copy import deepcopy
        source=model.parent
        data_path=source/'OpenSees_Complete_Model_Data_V118.json'
        config_path=source/'OpenSees_Complete_Model_Config_V118.json'
        meta_path=source/'OpenSees_Source_Model_Metadata_V118.json'
        if not data_path.is_file() or not config_path.is_file():
            raise ValueError('Fresh model data/config needed to compute full 1.0D+1.0L gravity. Rebuild from current ETABS export.')
        data=json.loads(data_path.read_text(encoding='utf-8-sig'))
        cfg=json.loads(config_path.read_text(encoding='utf-8-sig'))
        meta=json.loads(meta_path.read_text(encoding='utf-8-sig')) if meta_path.is_file() else {}
        selected=self.gravity_profile_var.get()
        if selected=='GRAVITY_1.0D_1.0L':
            if not data.get('unfactored_patterns'):
                raise ValueError('No unfactored pattern ledger. Rebuild ETABS export; cannot use 0.30 source preload as full gravity.')
            context=apply_gravity_profile(data,cfg,selected,meta.get('pattern_types',{}))
            total=float(data['total_downward_load_kN'])
        elif selected=='AS_CONFIGURED':
            context=apply_gravity_profile(data,cfg,selected,meta.get('pattern_types',{}))
            total=float(data['total_downward_load_kN'])
        else:
            raise ValueError('Unknown gravity profile '+str(selected))
        return total,context,cfg

    def _read_code_inputs(self, show_error=True):
        """Read literal support/load metadata embedded by the model exporter."""
        try:
            model = Path(self.model_var.get()).expanduser().resolve()
            report_path = model.parent / 'OpenSees_Complete_Export_Report_V118.json'
            if model.name.startswith('OpenSees_Complete_') and report_path.is_file():
                report = json.loads(report_path.read_text(encoding='utf-8-sig'))
                if report.get('assembly_errors'):
                    raise ValueError('Model assembly blocked: ' + '; '.join(report['assembly_errors']) + '\nRebuild the export after resolving these inputs. Report: ' + str(report_path))
            tree = ast.parse(model.read_text(encoding="utf-8-sig"), filename=str(model))
            data = None
            for node in tree.body:
                if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "GRAVITY_GUI_INPUTS" for t in node.targets):
                    data = ast.literal_eval(node.value)
                    break
            if not isinstance(data, dict):
                raise ValueError("This script has no GRAVITY_GUI_INPUTS metadata. Select a generated model that contains that dictionary, or enter support/load inputs manually only after reviewing the model script.")
            supports = [int(x) for x in data.get("support_node_tags", [])]
            total, context, cfg = self._selected_gravity_evidence(model)
            if not supports:
                raise ValueError("No fixed support node tags were found in the generated code.")
            self.position_support_var.set(", ".join(map(str, supports)))
            from components.gravity.etabs_reaction_support_filter import PROJECT_PRIMARY_32
            reaction_supports=sorted(PROJECT_PRIMARY_32)
            self.reaction_support_var.set(", ".join(map(str,reaction_supports)))
            self.reaction_support_verification_var.set(
                "32 project nodes predefined; original ETABS table not yet verified")
            source_table=self.etabs_full_table_var.get().strip()
            if source_table and Path(source_table).is_file():
                try:
                    from components.gravity.etabs_reaction_support_filter import classify_supports
                    model_data=json.loads((model.parent/'OpenSees_Complete_Model_Data_V118.json').read_text(encoding="utf-8-sig"))
                    topology=json.loads((model.parent/'OpenSees_Element_Connectivity.json').read_text(encoding="utf-8-sig"))
                    selected,filter_audit=classify_supports(source_table,topology,model_data['supports'])
                    reaction_supports=sorted(map(int,selected))
                    self.reaction_support_var.set(", ".join(map(str,reaction_supports)))
                    self.reaction_support_verification_var.set("PASS: 32 project nodes match original ETABS reactions and mapping")
                    self._gravity_action_log("ETABS_REACTION_FILTER",
                        f"Nonzero FZ support nodes={len(reaction_supports)}; excluded={filter_audit['released_support_count']}; original table={source_table}")
                except Exception as filter_error:
                    self.reaction_support_verification_var.set("NOT VERIFIED: "+str(filter_error))
                    if self._selected_wall_support_strategy()=="ETABS_NONZERO_REACTION_DIAGNOSTIC":
                        raise
            if self._selected_wall_support_strategy()=="ETABS_NONZERO_REACTION_DIAGNOSTIC":
                self.support_var.set(", ".join(map(str,reaction_supports)))
                if not source_table:
                    self.status_var.set("Main 32 nodes displayed; select completed ETABS 1. DL + LL table before running")
            else:
                self.support_var.set(", ".join(map(str,supports)))
            if total is not None: self.load_var.set(f"{float(total):.8f}")
            self._refresh_case_reaction()
            if data.get("load_steps"): self.steps_var.set(str(int(data["load_steps"])))
            note = data.get("load_total_units_note", "")
            coverage = data.get("coverage_note", "")
            if hasattr(self,"storey_tree"):self._show_storey_loads()
            self.status_var.set("Gravity profile "+context['profile']+"; applied="+str(total)+" kN. Seismic mass independent.")
            if show_error:
                messagebox.showinfo("Values read from generated code", f"Active support tags: {self.support_var.get() or 'Missing original ETABS table for primary 32-node filter'}\nOriginal mapped support count: {len(supports)}\nVertical gravity load total: {total} kN\n\n{note}\n{coverage}\n\nThis auto-total only sums loads present in the generated model script.", parent=self.win)
            return data
        except Exception as exc:
            self.support_var.set('')
            from components.gravity.etabs_reaction_support_filter import PROJECT_PRIMARY_32
            self.reaction_support_var.set(", ".join(map(str, sorted(PROJECT_PRIMARY_32))))
            self.reaction_support_verification_var.set("NOT VERIFIED: "+str(exc))
            self.position_support_var.set("")
            self.load_var.set('')
            self.solved_reaction_var.set("Not analyzed for this case")
            self.solved_reaction_status_var.set("Model input error — no verified reaction")
            if show_error: messagebox.showerror("Could not read gravity inputs", str(exc), parent=self.win)
            else: self.status_var.set(str(exc))
            return None


