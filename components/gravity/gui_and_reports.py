def _runner_source(model_script, result_path, support_nodes, applied_kN, nsteps, profile="GRAVITY_1.0D_1.0L"):
    return "\n".join([
        "# Generated by OpenSees_Gravity_GUI_V110.py",
        "import json, runpy, sys, traceback",
        "from pathlib import Path",
        f"MODEL_SCRIPT = Path({str(model_script)!r})",
        f"RESULT_PATH = Path({str(result_path)!r})",
        f"SUPPORT_NODES = {list(support_nodes)!r}",
        f"APPLIED_VERTICAL_LOAD_KN = {float(applied_kN)!r}",
        f"NSTEPS = {int(nsteps)!r}",
        f"GRAVITY_PROFILE = {str(profile)!r}",
        "sys.path.insert(0, str(MODEL_SCRIPT.parent))",
        "try:",
        "    if not MODEL_SCRIPT.is_file(): raise FileNotFoundError(MODEL_SCRIPT)",
        "    model_globals = runpy.run_path(str(MODEL_SCRIPT), run_name='__main__')",
        "    import openseespy.opensees as ops",
        "    from OpenSees_Analysis_Stack_V110 import run_gravity_stage",
        "    node_tags = [int(n) for n in ops.getNodeTags()]",
        "    element_tags = [int(e) for e in ops.getEleTags()]",
        "    # New V118 entries already run the gravity stage during construction.",
        "    # NEVER apply the same gravity source twice.",
        "    model_report = model_globals.get('MODEL_REPORT', {})",
        "    SUPPORT_NODES = [int(n) for n in model_report.get('gravity_base_support_tags', SUPPORT_NODES)]",
        "    WALL_SUPPORT_STRATEGY = model_report.get('gravity_support_strategy', 'ETABS_SOURCE_SUPPORTS')",
        "    ADDED_WALL_SUPPORTS = model_report.get('gravity_added_support_nodes', [])",
        "    print('[GRAVITY SUPPORT AUDIT]', json.dumps({'strategy':WALL_SUPPORT_STRATEGY, 'supports':len(SUPPORT_NODES), 'additional_mesh_supports':ADDED_WALL_SUPPORTS}),flush=True)",
        "    if isinstance(model_report, dict) and model_report.get('preload_completed'):",
        "        report_file = MODEL_SCRIPT.parent / 'OpenSees_Complete_Gravity_Check_V118.json'",
        "        if not report_file.is_file(): raise FileNotFoundError('Preloaded gravity report missing: ' + str(report_file))",
        "        report = json.loads(report_file.read_text(encoding='utf-8-sig'))",
        "    else:",
        "        report = run_gravity_stage(ops, SUPPORT_NODES, APPLIED_VERTICAL_LOAD_KN, model_nodes=node_tags, nsteps=NSTEPS, freeze=True, system='UmfPack', response_output_dir=RESULT_PATH.parent / 'Gravity_Response')",
        "    ops.reactions()",
        "    nodes = []",
        "    for n in node_tags:",
        "        xyz = list(ops.nodeCoord(n)); disp = list(ops.nodeDisp(n))",
        "        nodes.append({'tag':n, 'x_m':float(xyz[0]), 'y_m':float(xyz[1]), 'z_m':float(xyz[2]), 'ux_m':float(disp[0]), 'uy_m':float(disp[1]), 'uz_m':float(disp[2]), 'rx_rad':float(disp[3]), 'ry_rad':float(disp[4]), 'rz_rad':float(disp[5])})",
        "    reactions = [{'node_tag':n, 'rx_kN':float(ops.nodeReaction(n,1)), 'ry_kN':float(ops.nodeReaction(n,2)), 'rz_kN':float(ops.nodeReaction(n,3))} for n in SUPPORT_NODES]",
        "    elements = []",
        "    for e in element_tags:",
        "        try: en = [int(n) for n in ops.eleNodes(e)]",
        "        except Exception: continue",
        "        if len(en) >= 2: elements.append({'tag':e, 'nodes':en})",
        "    local_forces = []",
        "    for e in element_tags:",
        "        try: values = [float(x) for x in ops.eleResponse(e, 'localForce')]",
        "        except Exception: continue",
        "        if len(values) == 12:",
        "            local_forces.append({'tag':int(e), 'N_i_kN':values[0], 'Vy_i_kN':values[1], 'Vz_i_kN':values[2], 'T_i_kNm':values[3], 'My_i_kNm':values[4], 'Mz_i_kNm':values[5], 'N_j_kN':values[6], 'Vy_j_kN':values[7], 'Vz_j_kN':values[8], 'T_j_kNm':values[9], 'My_j_kNm':values[10], 'Mz_j_kNm':values[11]})",
        "    RESULT_PATH.write_text(json.dumps({'ok':True,'model_script':str(MODEL_SCRIPT),'report':report,'gravity_profile':GRAVITY_PROFILE,'wall_support_strategy':WALL_SUPPORT_STRATEGY,'added_wall_support_tags':ADDED_WALL_SUPPORTS,'support_node_tags':SUPPORT_NODES,'nodes':nodes,'reactions':reactions,'elements':elements,'local_forces':local_forces}, indent=2), encoding='utf-8')",
        "except Exception as exc:",
        "    RESULT_PATH.write_text(json.dumps({'ok':False,'error':str(exc),'traceback':traceback.format_exc()}, indent=2), encoding='utf-8')",
        "    traceback.print_exc(); sys.exit(1)",
    ]) + "\n"


