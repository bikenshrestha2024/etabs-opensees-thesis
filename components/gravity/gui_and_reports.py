    def _rebuild_verified_clear_beam(self, *, auto=False):
        """Recreate model in a new folder; never change original EDB/export.

        Auto mode is for the primary Run button only when a source has an
        explicitly unverified/gross beam policy. The required source workbook
        remains independently verified; no arbitrary guess is permitted.
        """
        if self._gravity_busy:
            messagebox.showwarning("Another process running",
                                   "Finish the current gravity process first.",
                                   parent=self.win)
            return
        model=Path(self.model_var.get()).expanduser()
        if not model.is_file():
            messagebox.showerror("Select source model","Select the current exported model first.",parent=self.win)
            return
        native=self.etabs_native_assignment_var.get().strip()
        if not native:
            # The completed ETABS full-table workbook may also contain the
            # original native material/frame/offset assignment sheets. Prefer
            # this previously selected candidate to another file dialog;
            # the native rebuild script independently verifies every sheet.
            candidate=self.etabs_full_table_var.get().strip()
            if candidate and Path(candidate).is_file() and Path(candidate).suffix.lower() in (".xlsx",".xlsm"):
                native=candidate
                self.etabs_native_assignment_var.set(native)
                self._gravity_action_log("AUTO_NATIVE_ASSIGNMENT_CANDIDATE",
                    "Reusing user-selected full ETABS export; sheet-level proof still required: "+native)
        if not native:
            native=filedialog.askopenfilename(
                parent=self.win,
                title="Original ETABS frame/material assignment workbook",
                filetypes=[("Original ETABS full assignment Excel","*.xlsx *.xlsm"),
                           ("All files","*.*")])
            if not native:return
            self.etabs_native_assignment_var.set(native)
        native_file=Path(native).expanduser()
        if not native_file.is_file() or native_file.suffix.lower() not in (".xlsx",".xlsm"):
            messagebox.showerror("Assignment workbook required",
                "Select the ORIGINAL ETABS full assignment Excel workbook, "
                "not NBC105_RS_Scaling or the gravity reactions summary.",
                parent=self.win)
            return
        destination=(str(model.resolve().parent.parent) if auto else
            filedialog.askdirectory(
                parent=self.win,
                title="Choose parent directory for NEW verified clear-beam source export"))
        if not destination:return
        source=model.resolve().parent
        import datetime as _dt
        parent_dir=Path(destination).resolve()
        if parent_dir==source or source in parent_dir.parents:
            proposed=source.parent/(
                "Verified_Clear_Beam_"+_dt.datetime.now().strftime("%Y%m%d_%H%M%S_%f"))
            approved=messagebox.askyesno(
                "Create separate export beside original source?",
                "Your selected destination is INSIDE the original ETABS export folder. "
                "The rebuild refuses to put a corrected source inside a source "
                "used for other gravity/ESM calculations.\n\n"
                "Create this NEW SIBLING folder instead?\n"+str(proposed)+
                "\n\nNo existing model or ETABS EDB will be changed.",
                parent=self.win)
            if not approved:
                self._set_gravity_operation("CANCELLED",
                    "Select an output folder OUTSIDE the original export")
                return
            new=proposed
        else:
            new=parent_dir/(
                "Verified_Clear_Beam_"+_dt.datetime.now().strftime("%Y%m%d_%H%M%S_%f"))
        # In an exported copy the runtime contains components but not tools.
        # Run the rebuilt source implementation from the current updated repo.
        current_root=Path(__file__).resolve().parents[2]
        script=current_root/"tools"/"REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py"
        if not script.is_file():
            # Automatically find the user's downloaded *updated* repository.
            # Never execute an arbitrary PATH script; require matching modules.
            candidates=[]
            home=Path.home()
            candidates.extend([
                home/"Downloads"/"etabs-opensees-thesis-main",
                home/"Downloads"/"etabs-opensees-thesis",
                home/"Documents"/"GitHub"/"etabs-opensees-thesis",
                home/"etabs-opensees-thesis",
            ])
            for item in (home/"Downloads", home/"Documents"):
                if item.is_dir():
                    candidates.extend(sorted(
                        (d for d in item.glob("etabs-opensees-thesis*") if d.is_dir()),
                        key=lambda d:d.stat().st_mtime,reverse=True))
            for candidate in candidates:
                found=candidate/"tools"/"REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py"
                if (found.is_file() and
                    (candidate/"components"/"model"/"assembly.py").is_file() and
                    (candidate/"components"/"validation"/"etabs_assignment_gravity_audit.py").is_file()):
                    script=found
                    self._gravity_action_log("AUTO_REBUILD_SCRIPT",str(script))
                    break
        if not script.is_file():
            # An old saved runtime does not own the live repository tools/.
            # Ask for the existing verified script instead of falsely looking
            # under C:/Users/User/tools. Never silently fall back to an
            # arbitrary similarly named file on PATH or in Downloads.
            messagebox.showinfo("Choose current GitHub rebuild script",
                "This gravity GUI is running from an older saved runtime.\n"
                "Browse to your UPDATED etabs-opensees-thesis repository, "
                "then select:\n"
                "tools/REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py\n\n"
                "The script will run with its own repository components. "
                "Your existing source export and ETABS EDB remain unchanged.",
                parent=self.win)
            chosen=filedialog.askopenfilename(
                parent=self.win,
                title="Select tools/REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py from UPDATED repo",
                filetypes=[("Python source","*.py")])
            if not chosen:return
            script=Path(chosen).expanduser().resolve()
        current_root=script.parent.parent
        if (script.name!="REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py"
                or script.parent.name!="tools"
                or not (current_root/"components"/"model"/"assembly.py").is_file()
                or not (current_root/"components"/"validation"/
                        "etabs_assignment_gravity_audit.py").is_file()):
            messagebox.showerror("Incorrect rebuild script",
                "Select the script located inside the NEW GitHub repository:\n"
                ".../etabs-opensees-thesis/tools/"
                "REBUILD_VERIFIED_CLEAR_BEAM_MODEL.py\n\n"
                "It must have the matching components/model and "
                "components/validation modules.\nSelected: "+str(script),
                parent=self.win)
            return
        self._gravity_busy=True
        self._set_gravity_operation("RUNNING","Verifying native ETABS workbook and rebuilding source")
        self._gravity_action_log("CORRECTED_EXPORT_START",
            "Old source="+str(source)+" | new target="+str(new))
        def worker():
            try:
                command=[str(self.python_var.get()),"-u",str(script),
                    "--source-dir",str(source),
                    "--assignment-workbook",str(native),
                    "--dest-dir",str(new)]
                proc=subprocess.run(command,cwd=str(current_root),
                    text=True,capture_output=True,errors="replace",encoding="utf-8")
                logfile=new/"CLEAR_BEAM_REBUILD_GUI.log"
                if new.is_dir():
                    logfile.write_text(proc.stdout+"\n"+proc.stderr,
                                       encoding="utf-8")
                success=proc.returncode==0 and (
                    new/"OpenSees_Complete_Gravity_Model.py").is_file()
                msg=(proc.stderr or proc.stdout or "No process output")[-4000:]
                def finished():
                    self._gravity_busy=False
                    if success:
                        self.model_var.set(str(new/"OpenSees_Complete_Gravity_Model.py"))
                        self._set_gravity_operation("FINISHED",
                            "New source ready; gravity not yet solved | "+str(new))
                        self.status_var.set("NEW verified clear-beam source selected. "
                            "Automatically refreshing gravity support lists and source loads.")
                        self._gravity_action_log("CORRECTED_EXPORT_FINISHED",str(new))
                        self._read_code_inputs(show_error=False)
                        if auto:
                            self._gravity_action_log("AUTO_REBUILD_AND_RUN",
                                "Source rebuilt; running with verified selected support scenario.")
                            self.run()
                            return
                        messagebox.showinfo("New corrected model",
                            "Native ETABS beam evidence checked and new model generated.\n"
                            "Old gravity results are unchanged.\n"
                            "Now click Read BOTH support lists, then rerun gravity.\n"+
                            str(new),parent=self.win)
                    else:
                        self._set_gravity_operation("BLOCKED",msg)
                        self._gravity_action_log("CORRECTED_EXPORT_BLOCKED",msg)
                        messagebox.showerror("Clear-beam rebuild blocked",msg,parent=self.win)
                self.win.after(0,finished)
            except Exception as exc:
                issue=str(exc)
                def failed():
                    self._gravity_busy=False
                    self._set_gravity_operation("BLOCKED",issue)
                    self._gravity_action_log("CORRECTED_EXPORT_BLOCKED",issue)
                self.win.after(0,failed)
        threading.Thread(target=worker,daemon=True).start()

