    def _gravity_action_log(self,stage,message):
        """Add bounded timestamped action messages to the existing Run log.

        [REF docs/review/GRAVITY_ETABS_COMPARISON.md] Audit API operations
        without changing analysis values or solver state.
        """
        stamp=datetime.now().astimezone().isoformat(timespec="seconds")
        line=f"[{stamp}] [{stage}] {message}"
        self.log.insert("end",line+"\n")
        self.log.see("end")
        try:
            target=Path(self.output_var.get()).expanduser().resolve()
            if target.is_dir():
                with (target/"Gravity_GUI_Actions.log").open("a",encoding="utf-8") as file:
                    file.write(line+"\n")
        except OSError:
            pass  # Logging must not interrupt the solver or output exports.
        self.win.update_idletasks()

    def _offline_etabs_table_compare(self):
        """Read previously completed ETABS spreadsheet; no COM or solver needed.

        [REF components/validation/gravity_etabs_offline.py]
        """
        try:
            source=Path(self.etabs_full_table_var.get()).expanduser().resolve()
            if not source.is_file():
                raise FileNotFoundError('Select the analyzed ETABS full table Excel export or Joint Reactions CSV')
            export_folder=Path(self.model_var.get()).expanduser().resolve().parent
            mapping=export_folder/'OpenSees_Element_Connectivity.json'
            if not mapping.is_file():
                raise FileNotFoundError('Missing source ETABS point mapping: '+str(mapping))
            main=Path(self.output_var.get()).expanduser().resolve()/'Gravity_Wall_Base_Comparison'
            runs=sorted((x for x in main.glob('*') if
                         (x/'ETABS_SOURCE_SUPPORTS'/'Gravity_Result_V110.json').is_file()),
                        reverse=True)
            if not runs:raise FileNotFoundError(
                'Run BOTH wall-base gravity strategies first to generate current source and continuous results')
            root=runs[0]
            a=root/'ETABS_SOURCE_SUPPORTS'/'Gravity_Result_V110.json'
            b=root/'CONTINUOUS_WALL_BASE_FIXED'/'Gravity_Result_V110.json'
            if not b.is_file():raise FileNotFoundError('Missing continuous wall base result: '+str(b))
            dst=root/'ETABS_Full_Table_Offline_Comparison'
            self.nb.select(self.log_tab)
            self._gravity_action_log('ETABS_OFFLINE_START',
                'Reading native ETABS joint reaction table without COM: '+str(source))
            self._gravity_action_log('ETABS_OFFLINE_INPUTS',
                'OpenSees source+continuous runs: '+str(root))
            th=threading.Thread(target=self._offline_etabs_worker,
                args=(source,mapping,a,b,dst),daemon=True)
            th.start()
        except Exception as exc:
            messagebox.showerror('Offline ETABS gravity comparison',str(exc),parent=self.win)

    def _offline_etabs_worker(self,source,mapping,a,b,dst):
        try:
            from components.validation.gravity_etabs_offline import (
                compare_etabs_export,export_offline_comparison)
            report=compare_etabs_export(source,mapping,a,b,
                                        case=self.etabs_case_var.get().strip())
            export_offline_comparison(report,dst)
            self.win.after(0,lambda:self._offline_etabs_finished(report,dst,None))
        except Exception as exc:
            error=traceback.format_exc()
            self.win.after(0,lambda:self._offline_etabs_finished(None,dst,error))

    def _offline_etabs_finished(self,report,dst,error):
        if error is not None:
            self._gravity_action_log('ETABS_OFFLINE_ERROR',error)
            self.status_var.set('Offline ETABS comparison failed; review Run log')
            messagebox.showerror('Offline ETABS comparison',error[-1800:],
                                 parent=self.win)
            return
        top=report['rows'][:6]
        self._gravity_action_log('ETABS_OFFLINE_OUTPUT',str(dst))
        self._gravity_action_log('ETABS_OFFLINE_COMPLETE',
            'ETABS unique joints='+str(report['etabs_joint_records'])+
            ', matched OpenSees='+str(report['matched_source_nodes'])+
            ', total force difference='+str(report['difference_opensees_minus_etabs_kN'])+
            ' kN; output='+str(dst))
        for row in top:
            self._gravity_action_log('ETABS_NODE',
                'ETABS unique '+str(row['etabs_unique_name'])+
                ' → OpenSees '+str(row['opensees_node_tag'])+
                '; difference kN='+str(row['delta_source_minus_etabs_kN'])+
                '; status='+row['status'])
        self.status_var.set('Offline ETABS table comparison saved: '+str(dst))
        try:
            self._publish_gravity_evidence(dual_run=dst.parent)
        except Exception as exc:
            self._gravity_action_log('EVIDENCE_EXPORT_ERROR',
                'Offline data saved; evidence ZIP failed: '+str(exc))
        messagebox.showinfo('Offline ETABS gravity comparison',
            f"ETABS joints: {report['etabs_joint_records']}\\n"
            f"Verified mapped supports: {report['matched_source_nodes']}\\n"
            f"Total OpenSees − ETABS: {report['difference_opensees_minus_etabs_kN']:+,.3f} kN\\n\\n"
            "See the full per-point Excel and CSV results in:\\n"+str(dst),
            parent=self.win)

    def _direct_etabs_gravity_compare(self):
        """Extract matching ETABS full gravity and compare without switching programs.

        [REF components/validation/gravity_etabs_direct.py connect_and_compare]
        """
        try:
            from components.validation.gravity_etabs_direct import connect_and_compare
            model=Path(self.model_var.get()).expanduser().resolve()
            if not model.is_file():raise ValueError("Select a generated OpenSees gravity model first")
            gravity=Path(self.output_var.get()).expanduser().resolve()/"Gravity_Result_V110.json"
            if not gravity.is_file():
                raise FileNotFoundError("Run OpenSees full-gravity analysis first: "+str(gravity))
            if self.gravity_profile_var.get()!="GRAVITY_1.0D_1.0L":
                raise ValueError("Direct gravity comparison requires GRAVITY_1.0D_1.0L")
            self.nb.select(self.log_tab)
            self._gravity_action_log("ETABS_START","Requesting direct ETABS/OpenSees gravity comparison")
            # COM runs on the main Tk thread. Owned ETABS instances are closed
            # in the direct API finally block, leaving user's ETABS untouched.
            self.status_var.set("Opening dedicated ETABS EDB and reading gravity results…")
            self.win.update_idletasks()
            comparison_out=gravity.parent/"Gravity_ETABS_OpenSees_Direct"
            alternate=bool(self.allow_alternate_edb.get())
            if self.run_missing_etabs_results.get():
                if not self.launch_etabs_for_gravity.get():
                    raise ValueError("Automatic analysis is permitted only for a private ETABS instance")
                if not messagebox.askyesno(
                    "Automatic ETABS analysis on a copy",
                    "If the selected ETABS EDB lacks gravity results, the program will "
                    "make a SHA256-verified working COPY of that EDB, then run ETABS "
                    "analysis on the copy.\\n\\n"
                    "ETABS may run ALL currently enabled cases, including time histories. "
                    "The original source EDB will not be saved or analyzed. "
                    "The working EDB and its analysis files remain in the output folder.\\n\\n"
                    "Proceed?",parent=self.win):
                    self._gravity_action_log("ETABS_CANCELLED",
                        "User declined automatic analysis on isolated EDB copy")
                    return
            if alternate and not messagebox.askyesno(
                "Diagnostic comparison only",
                "You selected a different ETABS EDB from the original OpenSees export.\\n\\n"
                "This comparison can report gravity-reaction DIFFERENCES but cannot "
                "verify that the two models have identical geometry, loads, materials or supports.\\n\\n"
                "Continue with unverified alternate-model provenance?",
                parent=self.win):
                return
            comp,out=connect_and_compare(model.parent,gravity,
                              case=self.etabs_case_var.get().strip(),output_dir=comparison_out,
                              allow_alternate_edb=alternate,
                              launch_new_etabs=bool(self.launch_etabs_for_gravity.get()),
                              etabs_edb_path=self.etabs_edb_path.get().strip() or None,
                              etabs_exe_path=self.etabs_exe_path.get().strip() or None,
                              run_if_missing=bool(self.run_missing_etabs_results.get()),
                              log_callback=lambda line:self._gravity_action_log("ETABS_API",line))
            self._gravity_action_log("ETABS_SUCCESS","Comparison JSON, CSV and Excel exported: "+str(out))
            self._gravity_action_log("ETABS_OUTPUT_ETABS_JSON",str(out/"etabs_gravity.json"))
            self._gravity_action_log("ETABS_OUTPUT_COMPARISON",str(out/"Direct_Gravity_Comparison.json"))
            self._gravity_action_log("ETABS_OUTPUT_EXCEL",str(out/"ETABS_OpenSees_Direct_Gravity_Comparison.xlsx"))
            self._gravity_action_log("ETABS_OUTPUT_NATIVE_LOGS",str(out/"ETABS_Native_Analysis_Logs"))
            self.etabs_gravity_json_var.set(str(out/"etabs_gravity.json"))
            self.status_var.set("Direct gravity comparison saved: "+str(out))
            try:
                self._publish_gravity_evidence()
            except Exception as pack_exc:
                self._gravity_action_log("EVIDENCE_EXPORT_ERROR",
                    "ETABS direct extraction saved; automatic ZIP failed: "+str(pack_exc))
            note=(f"ETABS FZ = {comp['etabs_base_FZ_kN']:.3f} kN\\n"
                  f"OpenSees RZ = {comp['opensees_support_FZ_kN']:.3f} kN\\n"
                  f"Difference = {comp['difference_kN']:.3f} kN "
                  f"({comp['percent_difference']:.4f}%)\\n\\n"
                  "This is a global reaction check, not engineering acceptance.\\n"
                  "Review partial support data and component loads.\\n"
                  "Model identity: "+str(comp.get('model_identity_status','UNVERIFIED')))
            ranked=comp.get('top_node_discrepancies',[])
            if ranked:
                note+="\\n\\nLargest verified support discrepancies (ETABS - OpenSees):"
                for row in ranked[:5]:
                    note+=f"\\nETABS {row['etabs_point']} / OpenSees {row['opensees_node']}: "
                    note+=f"{row['delta_etabs_minus_opensees_kN']:+.3f} kN"
            else:
                note+="\\n\\nNo one-to-one verified global-Z support pairs yet; review node audit."
            node_info=comp.get('node_comparison',{})
            if node_info:
                note+=f"\\nMatched verified pairs: {node_info.get('valid_one_to_one_global_z_count',0)}"
                note+=f" | Ambiguous: {node_info.get('ambiguous_count',0)}"
            messagebox.showinfo("Direct ETABS/OpenSees gravity comparison",note,parent=self.win)
        except Exception as exc:
            self._gravity_action_log("ETABS_ERROR",str(exc))
            self.nb.select(self.log_tab)
            self.status_var.set("Direct ETABS gravity extraction blocked: "+str(exc))
            messagebox.showerror("Direct ETABS gravity comparison",str(exc),parent=self.win)

