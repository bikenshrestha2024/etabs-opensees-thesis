def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--base-export", required=True)
    parser.add_argument("--etabs-support-csv", required=True)
    parser.add_argument("--etabs-reaction-table", required=True)
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--steps", type=Path)
    parser.add_argument("--only", default="")
    args = parser.parse_args(argv)
    steps = json.loads(args.steps.read_text(encoding="utf-8")) if args.steps else DEFAULT_STEPS
    only = {s.strip() for s in args.only.split(",") if s.strip()} or None
    run_ablation(args.base_export, args.etabs_support_csv, args.etabs_reaction_table,
                 args.out_dir, steps, only=only)


if __name__ == "__main__":
    main()
