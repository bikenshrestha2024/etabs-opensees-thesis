def merge_config(config, updates):
    """Return a copy of ``config`` with top-level keys replaced; None deletes a key.

    [REF docs/source/tools/etabs_comparison_ablation.py.md]
    """
    result = copy.deepcopy(config)
    for key, value in updates.items():
        if value is None:
            result.pop(key, None)
        else:
            result[key] = copy.deepcopy(value)
    return result


def read_etabs_reference(path):
    """Matched ETABS support reactions: {opensees_node: dict(point, x, y, etabs_kN)}.

    [REF docs/source/tools/etabs_comparison_ablation.py.md]
    """
    out = {}
    with Path(path).open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            if row["status"] != "MATCHED_GLOBAL_Z":
                continue
            out[int(row["opensees_node"])] = dict(
                point=str(row["etabs_point"]), x=float(row["x_m"]), y=float(row["y_m"]),
                etabs_kN=float(row["etabs_global_rz_kN"]))
    if not out:
        raise ValueError("No MATCHED_GLOBAL_Z rows in " + str(path))
    return out


def in_core(x, y, box=CORE_BOX):
    """True when the plan position lies in the core-wall box (inclusive).

    [REF docs/validation/run_findings/GRAVITY_SUPPORT_REACTIONS_AND_RAYLEIGH_20261121.md §2]
    """
    return box[0] - 1e-9 <= x <= box[1] + 1e-9 and box[2] - 1e-9 <= y <= box[3] + 1e-9


def compare_reactions(reactions, reference):
    """Per-support OpenSees minus ETABS FZ and summary statistics (kN).

    [REF docs/source/tools/etabs_comparison_ablation.py.md]
    ``reactions`` maps OpenSees node tag to vertical reaction (kN).
    """
    missing = sorted(set(reference) - set(reactions))
    if missing:
        raise ValueError(f"OpenSees result lacks reactions for matched nodes {missing[:5]}")
    rows = []
    for node, ref in sorted(reference.items()):
        os_kN = float(reactions[node])
        rows.append(dict(opensees_node=node, etabs_point=ref["point"], x_m=ref["x"], y_m=ref["y"],
                         group="CORE" if in_core(ref["x"], ref["y"]) else "PERIMETER",
                         etabs_kN=ref["etabs_kN"], opensees_kN=os_kN,
                         delta_os_minus_etabs_kN=os_kN - ref["etabs_kN"]))
    deltas = [r["delta_os_minus_etabs_kN"] for r in rows]
    worst = max(rows, key=lambda r: abs(r["delta_os_minus_etabs_kN"]))

    def total(group, key):
        return sum(r[key] for r in rows if r["group"] == group)

    summary = dict(
        support_count=len(rows),
        max_abs_diff_kN=abs(worst["delta_os_minus_etabs_kN"]),
        max_abs_diff_at=dict(etabs_point=worst["etabs_point"], opensees_node=worst["opensees_node"],
                             x_m=worst["x_m"], y_m=worst["y_m"], etabs_kN=worst["etabs_kN"],
                             opensees_kN=worst["opensees_kN"]),
        rms_diff_kN=math.sqrt(sum(d * d for d in deltas) / len(deltas)),
        sum_abs_diff_kN=sum(abs(d) for d in deltas),
        core_opensees_kN=total("CORE", "opensees_kN"), core_etabs_kN=total("CORE", "etabs_kN"),
        perimeter_opensees_kN=total("PERIMETER", "opensees_kN"),
        perimeter_etabs_kN=total("PERIMETER", "etabs_kN"),
        total_opensees_kN=sum(r["opensees_kN"] for r in rows),
        total_etabs_kN=sum(r["etabs_kN"] for r in rows),
        core_count=sum(r["group"] == "CORE" for r in rows),
        perimeter_count=sum(r["group"] == "PERIMETER" for r in rows),
        status=STATUS)
    return rows, summary


def lump_to_reference_supports(reactions, coordinates, reference, *, tolerance_m=1e-6):
    """Lump reactions of extra wall-base nodes onto the two adjacent reference supports.

    [REF docs/source/tools/etabs_comparison_ablation.py.md] An unmeshed ETABS wall
    (Wall Auto Mesh = Default, straight wall) has a linear bottom edge between its two
    restrained corner joints; a force at fraction t along that edge is carried (1 - t)
    by the first and t by the second corner (linear edge shape functions). ``reactions``
    and ``coordinates`` are keyed by OpenSees node; ``reference`` by matched node with
    x, y. Returns (lumped reactions keyed by reference node, lumping audit).
    """
    out = {node: float(reactions.get(node, 0.0)) for node in reference}
    points = {node: (ref["x"], ref["y"]) for node, ref in reference.items()}
    moved, audit = 0.0, []
    for node, value in reactions.items():
        if node in reference:
            continue
        x, y = coordinates[node][:2]
        best = None
        for a, pa in points.items():
            for b, pb in points.items():
                if a >= b:
                    continue
                dx, dy = pb[0] - pa[0], pb[1] - pa[1]
                length2 = dx * dx + dy * dy
                t = ((x - pa[0]) * dx + (y - pa[1]) * dy) / length2
                off = math.hypot(pa[0] + t * dx - x, pa[1] + t * dy - y)
                if 0.0 < t < 1.0 and off <= tolerance_m and (best is None or length2 < best[0]):
                    best = (length2, a, b, t)
        if best is None:
            raise ValueError(f"support node {node} at {x, y} lies on no edge between reference supports")
        _, a, b, t = best
        out[a] += (1.0 - t) * value
        out[b] += t * value
        moved += value
        audit.append(dict(node=node, x_m=x, y_m=y, reaction_kN=value, to=[a, b], t=t))
    return out, dict(lumped_node_count=len(audit), lumped_reaction_kN=moved, rows=audit)


def _runner_source_function():
    """Load ``_runner_source`` from the gravity GUI module without importing tkinter."""
    path = ROOT / "components" / "gravity" / "gui_and_reports.py"
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    node = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "_runner_source")
    namespace = {}
    exec(compile(ast.Module(body=[node], type_ignores=[]), str(path), "exec"), namespace)
    return namespace["_runner_source"]


def prepare_step(base_export, step_dir, updates):
    """Copy the export, apply config updates and reassemble with the repository runtime."""
    base_export, step_dir = Path(base_export), Path(step_dir)
    if step_dir.exists():
        raise FileExistsError(str(step_dir))
    shutil.copytree(base_export, step_dir, ignore=shutil.ignore_patterns("__pycache__", "Gravity_Response*"))
    config_path = step_dir / "OpenSees_Complete_Model_Config_V118.json"
    config = json.loads(config_path.read_text(encoding="utf-8-sig"))
    config = merge_config(config, updates)
    config_path.write_text(json.dumps(config, indent=2, default=str), encoding="utf-8")
    from components.model.assembly import prepare_complete_export
    prepare_complete_export(step_dir, runtime_dir=ROOT)
    report = json.loads((step_dir / "OpenSees_Complete_Export_Report_V118.json").read_text(encoding="utf-8-sig"))
    if report.get("assembly_errors"):
        raise RuntimeError("assembly errors: " + repr(report["assembly_errors"]))
    return report


def applied_full_gravity_kN(step_dir):
    """Total 1.0D+1.0L downward load the gravity GUI would pass for this export (kN)."""
    from components.model.assembly import apply_gravity_profile
    step_dir = Path(step_dir)
    data = json.loads((step_dir / "OpenSees_Complete_Model_Data_V118.json").read_text(encoding="utf-8-sig"))
    cfg = json.loads((step_dir / "OpenSees_Complete_Model_Config_V118.json").read_text(encoding="utf-8-sig"))
    meta_path = step_dir / "OpenSees_Source_Model_Metadata_V118.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8-sig")) if meta_path.is_file() else {}
    apply_gravity_profile(data, cfg, "GRAVITY_1.0D_1.0L", meta.get("pattern_types", {}))
    return float(data["total_downward_load_kN"])


def run_gravity(step_dir, etabs_reaction_table, *, timeout_s=3600, nsteps=10,
                strategy="ETABS_NONZERO_REACTION_DIAGNOSTIC"):
    """Run the GUI-generated gravity runner for one export in a child process."""
    step_dir = Path(step_dir).resolve()
    out = step_dir / "Gravity_Ablation_Run"
    out.mkdir(exist_ok=True)
    result = out / "Gravity_Result_V110.json"
    model = step_dir / "OpenSees_Complete_Gravity_Model.py"
    total = applied_full_gravity_kN(step_dir)
    runner = out / "Gravity_Run_V110.py"
    from components.gravity.etabs_reaction_support_filter import PROJECT_PRIMARY_32
    runner.write_text(_runner_source_function()(model, result, sorted(PROJECT_PRIMARY_32), total,
                                                nsteps, "GRAVITY_1.0D_1.0L"), encoding="utf-8")
    env = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1",
               OPENSEES_GRAVITY_PROFILE="GRAVITY_1.0D_1.0L", OPENSEES_GRAVITY_GUI_MODE="1",
               OPENSEES_GRAVITY_WALL_SUPPORT_STRATEGY=strategy,
               OPENSEES_GRAVITY_ETABS_TABLE=str(Path(etabs_reaction_table).resolve()),
               OPENSEES_GRAVITY_AUDIT_DIR=str(out))
    start = time.perf_counter()
    with (out / "Gravity_Run_V110.log").open("w", encoding="utf-8") as log:
        proc = subprocess.run([sys.executable, str(runner)], cwd=str(out), env=env,
                              stdout=log, stderr=subprocess.STDOUT, timeout=timeout_s)
    payload = json.loads(result.read_text(encoding="utf-8"))
    if proc.returncode or not payload.get("ok"):
        raise RuntimeError("gravity run failed: " + str(payload.get("error")))
    return payload, total, time.perf_counter() - start


def run_ablation(base_export, etabs_support_csv, etabs_reaction_table, out_dir, steps, *, only=None):
    """Run the steps sequentially; write per-step comparison JSON/CSV and a summary JSON."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    reference = read_etabs_reference(etabs_support_csv)
    summary_path = out_dir / "ABLATION_SUMMARY.json"
    summary = json.loads(summary_path.read_text(encoding="utf-8")) if summary_path.is_file() else {
        "status": STATUS, "steps": {}}
    for step in steps:
        name = step["name"]
        if only and name.split("_")[0] not in only and name not in only:
            continue
        step_dir = out_dir / "steps" / name
        print("[ABLATION STEP START]", name, flush=True)
        report = prepare_step(base_export, step_dir, step["updates"])
        strategy = step.get("support_strategy", "ETABS_NONZERO_REACTION_DIAGNOSTIC")
        payload, total, seconds = run_gravity(step_dir, etabs_reaction_table, strategy=strategy)
        reactions = {int(r["node_tag"]): float(r["rz_kN"]) for r in payload["reactions"]}
        lumping = None
        if step.get("lump_to_reference"):
            coordinates = {int(n["tag"]): (n["x_m"], n["y_m"], n["z_m"]) for n in payload["nodes"]}
            reactions, lumping = lump_to_reference_supports(reactions, coordinates, reference)
        rows, stats = compare_reactions(reactions, reference)
        stats.update(support_strategy=strategy, wall_base_lumping=(
            {k: v for k, v in lumping.items() if k != "rows"} if lumping else None))
        stats.update(applied_total_kN=total, solver_seconds=seconds,
                     solver_report_status=payload["report"].get("status"),
                     equilibrium_error_percent=payload["report"].get("equilibrium_error_percent"),
                     stiffness_basis=payload["report"].get("stiffness_basis"),
                     support_count_solved=len(payload["reactions"]),
                     updates=step["updates"],
                     rigid_end_zones=report.get("rigid_end_zones"),
                     elastic_etabs_comparison=report.get("elastic_etabs_comparison"),
                     wall_max_cell_size_m=report.get("wall_max_cell_size_m"),
                     total_downward_load_kN_export=report.get("total_downward_load_kN"))
        (step_dir / "Gravity_Ablation_Run" / "REACTION_COMPARISON.json").write_text(
            json.dumps(dict(summary=stats, rows=rows), indent=2), encoding="utf-8")
        with (out_dir / f"{name}_reactions.csv").open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
        summary["steps"][name] = dict(summary=stats, rows=rows)
        summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
        print("[ABLATION STEP OK]", name, json.dumps({k: stats[k] for k in (
            "max_abs_diff_kN", "rms_diff_kN", "core_opensees_kN", "perimeter_opensees_kN",
            "total_opensees_kN")}), flush=True)
    return summary


def first_translational_modes(modal_result):
    """Pick the first mode with the largest UX and with the largest UY participation share.

    [REF components/modal/analysis.py run_nbc105_modal_audit] heuristic candidate only;
    returns {axis: dict(mode, period_s, participation_percent)} for the lowest mode whose
    directional participation exceeds every other direction and 10 %.
    """
    out = {}
    for axis, key, others in (("X", "UX_participation_percent", ("UY_participation_percent", "RZ_participation_percent")),
                              ("Y", "UY_participation_percent", ("UX_participation_percent", "RZ_participation_percent"))):
        for row in modal_result["rows"]:
            value = row.get(key) or 0.0
            if value >= 10.0 and all(value > (row.get(o) or 0.0) for o in others):
                out[axis] = dict(mode=row["mode"], period_s=row["period_s"], participation_percent=value,
                                 classification=row.get("classification_candidate"))
                break
    return out


def run_rayleigh(step_dir, awx, awy, empirical_settings, out_dir, *, timeout_s=3600):
    """Run ``components.modal.rayleigh.run`` for one export in a child process."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    script = out_dir / "Rayleigh_Run.py"
    script.write_text("\n".join([
        "import json, sys",
        f"sys.path.insert(0, {str(ROOT)!r})",
        "from components.modal.rayleigh import run",
        f"result = run({str(Path(step_dir).resolve())!r}, {float(awx)!r}, {float(awy)!r}, limit_state='ULS',",
        f"             output_dir={str(out_dir.resolve())!r}, empirical_settings={dict(empirical_settings)!r})",
        f"open({str((out_dir / 'RAYLEIGH_RESULT.json').resolve())!r}, 'w').write(json.dumps(result, indent=2))",
    ]) + "\n", encoding="utf-8")
    with (out_dir / "Rayleigh_Run.log").open("w", encoding="utf-8") as log:
        proc = subprocess.run([sys.executable, str(script)], cwd=str(out_dir), stdout=log,
                              stderr=subprocess.STDOUT, timeout=timeout_s)
    if proc.returncode:
        raise RuntimeError("Rayleigh run failed; see " + str(out_dir / "Rayleigh_Run.log"))
    return json.loads((out_dir / "RAYLEIGH_RESULT.json").read_text(encoding="utf-8"))


